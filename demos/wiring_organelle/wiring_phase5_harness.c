/*
 * MicroGPT-C — Phase 5 compositional held-out harness
 *
 * Runs `wiring_compositional_search` over the 30-prompt held-out
 * (`pipeline_corpus_compositional_test.txt`), dispatches each verified
 * graph through `pipeline_execute_vm`, scores against the reference
 * oracle in `wiring_references.c`, and reports per-axis stats.
 *
 * Usage:
 *   ./wiring_phase5_harness [held-out-path]
 *
 * Default held-out path: `pipeline_corpus_compositional_test.txt` next
 * to the binary (CMake POST_BUILD copies it for us).
 *
 * Per-axis scoring:
 *   Axis 1 = prompts 1..10 (2-primitive novel pairs)
 *   Axis 2 = prompts 11..20 (3-primitive synonym stress)
 *   Axis 3 = prompts 21..30 (composition + outer transform)
 *
 * Correctness threshold: a prompt counts as "correct" if the executed
 * answer matches the reference for at least 3 of 5 input sets — same
 * threshold as Phase 7.
 *
 * Copyright (c) 2026 Ajay Soni, Enjector Software Ltd. MIT License.
 */

