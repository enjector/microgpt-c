/* ============================================================
 *  VM-native wrappers around the wiring primitives.
 * ============================================================
 *
 * The wiring_natives.c registry uses `int64_t(int, const int64_t *)`.
 * The VM ABI uses `double(int, const double *)`. One wrapper per
 * manifest entry casts the doubles to int64, computes, and casts the
 * result back to double.  Generated by macro to keep the source short.
 */

/* Local re-implementations matching wiring_natives.c — kept in sync. */
static int64_t hp_clamp_(int64_t x, int64_t lo, int64_t hi) {
    return x < lo ? lo : (x > hi ? hi : x);
}

/* Each wrapper casts double[]→int64[], computes, casts result→double. */
static double hp_add(int argc, const double *a) {
    (void)argc; return (double)((int64_t)a[0] + (int64_t)a[1]);
}
static double hp_subtract(int argc, const double *a) {
    (void)argc; return (double)((int64_t)a[0] - (int64_t)a[1]);
}
static double hp_multiply(int argc, const double *a) {
    (void)argc; return (double)((int64_t)a[0] * (int64_t)a[1]);
}
static double hp_divide(int argc, const double *a) {
    (void)argc;
    int64_t y = (int64_t)a[1];
    return (double)(y == 0 ? 0 : (int64_t)a[0] / y);
}
static double hp_negate(int argc, const double *a) {
    (void)argc; return (double)(-(int64_t)a[0]);
}
static double hp_abs_val(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0]; return (double)(x < 0 ? -x : x);
}
static double hp_square(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0]; return (double)(x * x);
}
static double hp_cube(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0]; return (double)(x * x * x);
}
static double hp_double_val(int argc, const double *a) {
    (void)argc; return (double)((int64_t)a[0] * 2);
}
static double hp_triple_val(int argc, const double *a) {
    (void)argc; return (double)((int64_t)a[0] * 3);
}
static double hp_min_two(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0], y = (int64_t)a[1];
    return (double)(x < y ? x : y);
}
static double hp_max_two(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0], y = (int64_t)a[1];
    return (double)(x > y ? x : y);
}
static double hp_average_two(int argc, const double *a) {
    (void)argc; return (double)(((int64_t)a[0] + (int64_t)a[1]) / 2);
}
static double hp_distance_1d(int argc, const double *a) {
    (void)argc; int64_t d = (int64_t)a[0] - (int64_t)a[1];
    return (double)(d < 0 ? -d : d);
}
static double hp_midpoint(int argc, const double *a) {
    (void)argc; return (double)(((int64_t)a[0] + (int64_t)a[1]) / 2);
}
static double hp_mse(int argc, const double *a) {
    (void)argc; int64_t d = (int64_t)a[0] - (int64_t)a[1];
    return (double)(d * d);
}
static double hp_clamp(int argc, const double *a) {
    (void)argc; return (double)hp_clamp_((int64_t)a[0], (int64_t)a[1], (int64_t)a[2]);
}
static double hp_lerp(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0], y = (int64_t)a[1], t = (int64_t)a[2];
    return (double)(x + ((y - x) * t) / 100);
}
static double hp_sigmoid(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0];
    if (x <= -8) return 0;
    if (x >= 8)  return 100;
    static const int tbl[] = { 0,0,1,2,4,7,12,18,27,37,50,62,73,81,88,92,95,98,99,99,100 };
    int idx = (int)x + 10;
    if (idx < 0) idx = 0;
    if (idx > 20) idx = 20;
    return (double)tbl[idx];
}
static double hp_relu(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0]; return (double)(x > 0 ? x : 0);
}
static double hp_tax_amount(int argc, const double *a) {
    (void)argc; return (double)(((int64_t)a[0] * (int64_t)a[1]) / 100);
}
static double hp_apply_tax(int argc, const double *a) {
    (void)argc; int64_t x = (int64_t)a[0], r = (int64_t)a[1];
    return (double)(x - (x * r) / 100);
}
static double hp_percentage(int argc, const double *a) {
    (void)argc; int64_t y = (int64_t)a[1];
    return (double)(y == 0 ? 0 : ((int64_t)a[0] * 100) / y);
}
static double hp_discount(int argc, const double *a) {
    (void)argc; int64_t p = (int64_t)a[0], r = (int64_t)a[1];
    return (double)(p - (p * r) / 100);
}
static double hp_markup(int argc, const double *a) {
    (void)argc; int64_t p = (int64_t)a[0], r = (int64_t)a[1];
    return (double)(p + (p * r) / 100);
}
static double hp_compound(int argc, const double *a) {
    (void)argc; int64_t p = (int64_t)a[0], rt = (int64_t)a[1], n = (int64_t)a[2];
    if (n < 0) n = 0; if (n > 30) n = 30;
    int64_t v = p;
    for (int64_t i = 0; i < n; i++) v = v + (v * rt) / 100;
    return (double)v;
}
static double hp_present_value(int argc, const double *a) {
    (void)argc; int64_t f = (int64_t)a[0], rt = (int64_t)a[1], n = (int64_t)a[2];
    if (n < 0) n = 0; if (n > 30) n = 30;
    int64_t v = f;
    for (int64_t i = 0; i < n; i++) v = (v * 100) / (100 + rt);
    return (double)v;
}
static double hp_future_value(int argc, const double *a) {
    return hp_compound(argc, a);
}
static double hp_factorial(int argc, const double *a) {
    (void)argc; int64_t n = (int64_t)a[0];
    if (n < 0) return 0;
    int64_t v = 1;
    for (int64_t i = 2; i <= n && i <= 20; i++) v *= i;
    return (double)v;
}
static double hp_fibonacci(int argc, const double *a) {
    (void)argc; int64_t n = (int64_t)a[0];
    if (n < 0) return 0;
    if (n < 2) return (double)n;
    int64_t prev = 0, cur = 1;
    for (int64_t i = 2; i <= n && i <= 90; i++) {
        int64_t nx = prev + cur; prev = cur; cur = nx;
    }
    return (double)cur;
}
static double hp_gcd(int argc, const double *a) {
    (void)argc;
    int64_t x = (int64_t)a[0]; if (x < 0) x = -x;
    int64_t y = (int64_t)a[1]; if (y < 0) y = -y;
    while (y) { int64_t t = y; y = x % y; x = t; }
    return (double)x;
}
static double hp_harmonic_n(int argc, const double *a) {
    (void)argc; int64_t n = (int64_t)a[0];
    if (n <= 0) return 0;
    int64_t s = 0;
    for (int64_t k = 1; k <= n && k <= 1000; k++) s += 1000 / k;
    return (double)s;
}
static double hp_circle_area(int argc, const double *a) {
    (void)argc; int64_t r = (int64_t)a[0];
    return (double)((314 * r * r) / 100);
}
static double hp_kinetic_energy(int argc, const double *a) {
    (void)argc; int64_t m = (int64_t)a[0], v = (int64_t)a[1];
    return (double)((m * v * v) / 2);
}
static double hp_bmi(int argc, const double *a) {
    (void)argc; int64_t w = (int64_t)a[0], h = (int64_t)a[1];
    return (double)(h == 0 ? 0 : (w * 10000) / (h * h));
}
static double hp_power(int argc, const double *a) {
    (void)argc; int64_t b = (int64_t)a[0], e = (int64_t)a[1];
    if (e < 0) return 0;
    int64_t v = 1;
    for (int64_t i = 0; i < e && i < 20; i++) v *= b;
    return (double)v;
}

